import assert from 'node:assert/strict';
import {matchesPeriod,participationNotes,needsChecking,occurrenceDate,planType,eventTime,socialContext,matchingDates,matchesCost} from '../app/browse.mjs';
const monday=new Date('2026-10-26T10:00:00+08:00');
assert(matchesPeriod({dates:['2026-10-31']},'weekend',monday));
assert(!matchesPeriod({dates:['2026-11-07']},'weekend',monday));
assert(!matchesPeriod({dates:['2026-10-27']},'today',monday));
assert(matchesPeriod({dates:['2026-10-26']},'today',monday));
const sunday=new Date('2026-11-01T10:00:00+08:00');
assert(!matchesPeriod({dates:['2026-10-31']},'weekend',sunday));
assert(matchesPeriod({dates:['2026-11-01']},'weekend',sunday));
const overnight={dates:['2026-11-01'],endAt:'2026-11-02T00:30:00+08:00'};
assert(matchesPeriod(overnight,'today',new Date('2026-11-02T00:15:00+08:00')));
assert(!matchesPeriod(overnight,'today',new Date('2026-11-02T01:00:00+08:00')));
assert.deepEqual(participationNotes({desc:'For ages 18–35. Registration required.'}),['Ages 18–35','Registration required']);
assert.deepEqual(participationNotes({desc:'Individuals and groups are welcome. RSVP required.'}),['Individuals & groups welcome','RSVP required']);
assert.deepEqual(participationNotes({desc:'Enjoy an evening with neighbours.'}),[]);
console.log('Passed Singapore quick-date filters, overnight boundaries and evidence-based participation labels.');

assert(needsChecking({dateRangeOnly:true}));
assert(needsChecking({factCheck:{status:'unverified'}}));
assert(!needsChecking({factCheck:{status:'partial'},price:'Check original listing'}));
const multi={dates:['2026-10-30','2026-10-31'],endAt:'2026-11-01T01:00:00+08:00'};
assert.equal(occurrenceDate(multi,'2026-10-31','all',monday),'2026-10-31');
assert.equal(occurrenceDate(multi,'all','weekend',monday),'2026-10-31');
assert.equal(occurrenceDate(multi,'2026-11-01','all',monday),'2026-11-01');
assert.equal(planType({category:'Bars & nightlife',desc:'DJ night'}),'activity');
assert.equal(planType({connectionType:'meet-people'}),'meet');
console.log('Passed confirmation rules, selected-date consistency and explicit social labels.');

const timed={dates:['2026-10-31'],when:'31 Oct · 9pm–midnight',calendarTime:{end:'00:00'}};
assert.equal(eventTime(timed,'2026-10-31'),'9pm–midnight');
assert.equal(eventTime({...timed,calendarTime:{end:'01:00'}},'2026-11-01'),'Until 01:00 · continues from the previous day');
assert.equal(eventTime({...timed,when:'Check session times'},'2026-10-31'),'Check session times');
const social={connectionType:'meet-people',verificationStatus:'confirmed',desc:'Meet over tea and conversation. RSVP required.'};
assert(socialContext(social).askSolo,'A social category alone must not promise solo admission');
assert(!socialContext({...social,desc:'Board games for individuals and groups. RSVP required.'}).askSolo);
assert.equal(socialContext({...social,verificationStatus:'unverified'}),null,'Do not promote unverified social arrangements');
assert.equal(socialContext({...social,connectionType:'activity'}),null);
console.log('Passed concise schedule display and confirmed-only social guidance without inferred solo admission.');

assert(matchesPeriod({dates:['2026-10-31']},'week',monday));
assert(!matchesPeriod({dates:['2026-11-02']},'week',monday),'Next Monday is outside the current week');
assert(!matchesPeriod({dates:['2026-10-25']},'week',monday),'Finished events do not appear in this week');
assert(matchesPeriod({dates:['2026-11-02']},'all',monday));
assert(matchesPeriod({dates:['2026-11-01'],endAt:'2026-11-02T02:00:00+08:00'},'week',new Date('2026-11-02T01:00:00+08:00')),'Overnight Sunday event carries into the new week');
console.log('Passed weekly versus all-upcoming date filters and Singapore overnight boundaries.');

const show={dates:['2026-11-03','2026-11-05','2026-11-06','2026-11-07','2026-11-08','2026-11-10']};
const thursday=new Date('2026-11-05T12:00:00+08:00');
assert.deepEqual(matchingDates(show,'all','all',thursday),['2026-11-05','2026-11-06','2026-11-07','2026-11-08','2026-11-10']);
assert.deepEqual(matchingDates(show,'all','weekend',thursday),['2026-11-07','2026-11-08']);
assert.deepEqual(matchingDates(show,'2026-11-10','all',thursday),['2026-11-10']);
assert.deepEqual(matchingDates(show,'all','today',thursday),['2026-11-05']);
assert.deepEqual(matchingDates(show,'all','week',thursday),['2026-11-05','2026-11-06','2026-11-07','2026-11-08']);
assert(matchesCost({entryCost:{kind:'paid',from:68}},'over20'));
assert(!matchesCost({entryCost:{kind:'paid',from:20}},'over20'));
assert(!matchesCost({entryCost:{kind:'unknown'}},'over20'));
assert(matchesCost({entryCost:{kind:'free',from:0}},'low'));
console.log('Passed repeat-date selection against filters and explicit entry-price ranges.');
