import assert from 'node:assert/strict';
import {singaporeDate,weekBounds,isPast,inWeek,nextDate} from '../dist/lifecycle.mjs';
const now=s=>new Date(s);
assert.equal(singaporeDate(now('2026-10-25T16:01:00Z')),'2026-10-26');
assert.deepEqual(weekBounds(now('2026-11-01T15:59:00Z')),{start:'2026-10-26',end:'2026-11-01',today:'2026-11-01'});
assert.equal(weekBounds(now('2026-11-01T16:01:00Z')).start,'2026-11-02');
const unknownTime={dates:['2026-10-30']};assert.equal(isPast(unknownTime,now('2026-10-30T15:59:59Z')),false);assert.equal(isPast(unknownTime,now('2026-10-30T16:00:00Z')),true);
const overnight={dates:['2026-11-01'],endAt:'2026-11-02T00:30:00+08:00'};assert.equal(isPast(overnight,now('2026-11-02T00:15:00+08:00')),false);assert.equal(isPast(overnight,now('2026-11-02T00:31:00+08:00')),true);assert.equal(inWeek(overnight,now('2026-11-02T00:15:00+08:00')),true);
const multi={dates:['2026-10-30','2026-11-06','2026-11-09']};assert.equal(isPast(multi,now('2026-11-02T09:00:00+08:00')),false);assert.equal(inWeek(multi,now('2026-11-02T09:00:00+08:00')),true);assert.equal(nextDate(multi,now('2026-11-02T09:00:00+08:00')),'2026-11-06');
const timed={dates:['2026-10-30'],endAt:'2026-10-30T21:00:00+08:00'};assert.equal(isPast(timed,now('2026-10-30T21:01:00+08:00')),true);
console.log('Passed Singapore timezone, weekly rollover, last-day, overnight, multi-date carryover and known finishing-time checks.');
const {eventDates}=await import('../dist/lifecycle.mjs');
assert.deepEqual(eventDates(overnight),['2026-11-01','2026-11-02']);
assert.equal(nextDate(overnight,now('2026-11-02T00:15:00+08:00')),'2026-11-02');
assert.equal(inWeek(overnight,now('2026-11-02T00:31:00+08:00')),false);
const unsorted={dates:['2026-11-09','2026-10-30','2026-11-06']};
assert.equal(inWeek(unsorted,now('2026-11-02T09:00:00+08:00')),true);
assert.equal(eventDates(unsorted).includes('2026-11-02'),false);
console.log('Passed overnight date-filter and unsorted schedule checks.');
